export function createTranslator(language: Language) {
  return (message: string, values: Record<string, string | number> = {}) => {
    const translated = values.count === 1 && Object.hasOwn(singular[language], message)
      ? singular[language][message]
      : language === 'fr' && Object.hasOwn(french, message) ? french[message] : message
    return translated.replace(/\{(\w+)\}/g, (placeholder, key: string) => String(values[key] ?? placeholder))
  }
}
